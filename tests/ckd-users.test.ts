function temp(t: { after(fn: () => void): void }) { const root = fs.mkdtempSync(path.join(os.tmpdir(), 'ckd-users-')); t.after(() => fs.rmSync(root, { recursive: true, force: true })); return root; }
const password = 'my long personal password 你好';

test('users persist only salted hashes; account identity is immutable, reserved and unique even when disabled', async t => {
  const root = temp(t), store = new UserStore(root, 'SystemAdmin');
  await assert.rejects(store.create('111')); await assert.rejects(store.create('systemadmin')); await assert.rejects(store.create('../bad'));
  const result = await store.create('Alice');
  assert.equal(result.initialPassword.length, 20); assert.equal(result.user.mustChangePassword, true); assert.equal('passwordHash' in result.user, false);
  const bytes = fs.readFileSync(path.join(root, 'ckd/users/users.json'), 'utf8');
  assert.ok(!bytes.includes(result.initialPassword)); assert.ok(!bytes.includes('SystemAdmin')); assert.equal(fs.statSync(path.join(root, 'ckd/users/users.json')).mode & 0o777, 0o600);
  assert.ok(await verifyUserPassword(result.initialPassword, store.get(result.user.id)!.passwordHash));
  store.setEnabled(result.user.id, false);
  await assert.rejects(new UserStore(root, 'SystemAdmin').create('alice'), /已存在/u);
  assert.equal(new UserStore(root).get(result.user.id)!.enabled, false);
  const racing = await Promise.allSettled([store.create('Race'), new UserStore(root, 'SystemAdmin').create('race')]);
  assert.equal(racing.filter(result => result.status === 'fulfilled').length, 1);
  assert.equal(store.list().filter(user => user.account.toLowerCase() === 'race').length, 1);
  assert.throws(() => store.setEnabled('system-admin', false)); await assert.rejects(store.reset('system-admin'));
  fs.mkdirSync(path.join(root, 'ckd/users/write.lock')); fs.writeFileSync(path.join(root, 'ckd/users/write.lock/owner.json'), JSON.stringify({ pid: process.pid }));
  assert.throws(() => store.setEnabled(result.user.id, true), /正在更新/u);
  fs.rmSync(path.join(root, 'ckd/users/write.lock'), { recursive: true });
  fs.writeFileSync(path.join(root, 'ckd/users/users.json'), 'broken registry');
  assert.throws(() => store.list(), /未被覆盖/u); await assert.rejects(store.create('Other'), /未被覆盖/u);
  assert.equal(fs.readFileSync(path.join(root, 'ckd/users/users.json'), 'utf8'), 'broken registry');
});

test('temporary sessions cannot use SOP, old clients must upgrade, password reset/disable revoke every session', async t => {
  const root = temp(t), access = new ClientAccess(root), created = await access.users.create('Alice');
  await assert.rejects(access.login({ account: 'Alice', password: created.initialPassword }), /升级/u);
  for (let i = 0; i < 10; i++) await assert.rejects(access.login({ account: 'Alice', password: created.initialPassword }), /升级/u);
  const initial = await access.login({ account: 'Alice', password: created.initialPassword }, true), header = 'Bearer ' + initial.token;
  assert.equal(access.me(header).mustChangePassword, true); assert.throws(() => access.authenticate(header), /初始密码/u);
  await assert.rejects(access.changePassword(header, { currentPassword: created.initialPassword, newPassword: 'short' }), /15/u);
  await assert.rejects(access.changePassword(header, { currentPassword: 'wrong', newPassword: password }), /原密码/u);
  await assert.rejects(access.changePassword(header, { currentPassword: created.initialPassword, newPassword: password, userId: 'other' }));
  await access.changePassword(header, { currentPassword: created.initialPassword, newPassword: password });
  assert.throws(() => access.me(header), /失效/u);
  await assert.rejects(access.login({ account: 'Alice', password: created.initialPassword }), /账号或密码/u);
  const first = await access.login({ account: 'Alice', password }), second = await access.login({ account: 'Alice', password });
  access.users.setEnabled(created.user.id, false);
  assert.throws(() => access.authenticate('Bearer ' + first.token), /失效/u); assert.throws(() => access.authenticate('Bearer ' + second.token), /失效/u);
  access.users.setEnabled(created.user.id, true);
  assert.throws(() => access.authenticate('Bearer ' + first.token), /失效/u);
  const pendingLogin = access.login({ account: 'Alice', password });
  access.users.setEnabled(created.user.id, false);
  await assert.rejects(pendingLogin, /账号或密码/u);
  access.users.setEnabled(created.user.id, true);
  await assert.rejects(access.login({ account: '111', password: '222' }), /账号或密码/u);
  const active = await access.login({ account: 'Alice', password });
  const reset = await access.users.reset(created.user.id);
  assert.throws(() => access.authenticate('Bearer ' + active.token), /失效/u);
  await assert.rejects(access.login({ account: 'Alice', password }), /账号或密码/u);
  const restricted = await access.login({ account: 'Alice', password: reset.initialPassword }, true);
  assert.equal(restricted.mustChangePassword, true); access.logout('Bearer ' + restricted.token);
  assert.throws(() => access.me('Bearer ' + restricted.token), /失效/u);
  assert.equal(new ClientAccess(root).users.list().length, 1);
});

test('ordinary login and change-password attempts are rate limited without blocking the event loop', async t => {
  const root = temp(t); let now = 0; const access = new ClientAccess(root, () => now);
  const created = await access.users.create('Alice');
  for (let i = 0; i < 10; i++) await assert.rejects(access.login({ account: 'Alice', password: 'bad' }), /错误/u);
  await assert.rejects(access.login({ account: 'Alice', password: created.initialPassword }, true), /次数过多/u);
  now += 5 * 60000;
  let tick = false; const timer = setTimeout(() => { tick = true; }, 5);
  const logged = await access.login({ account: 'Alice', password: created.initialPassword }, true); clearTimeout(timer);
  assert.ok(tick); assert.equal(logged.mustChangePassword, true);
});

